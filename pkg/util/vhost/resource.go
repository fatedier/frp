package vhost

import (
	"bytes"
	"io"
	"net/http"
	"os"

	"github.com/fatedier/frp/pkg/util/log"
	"github.com/fatedier/frp/pkg/util/version"
)

var NotFoundPagePath = ""

// CustomErrorPage defines a custom error page for a specific HTTP status code.
// It is used for errors generated by frps itself, such as 404 (no route found)
// and 504 (proxy timeout).
type CustomErrorPage struct {
	// ContentType is the Content-Type of the response. If empty, "text/html"
	// will be used.
	ContentType string
	// Body is the inline response body.
	Body string
	// Headers contains additional response headers.
	Headers map[string]string
}

var customErrorPages = make(map[int]CustomErrorPage)

// SetCustomErrorPages registers custom error pages keyed by HTTP status code.
func SetCustomErrorPages(pages map[int]CustomErrorPage) {
	customErrorPages = pages
}

const (
	NotFound = `<!DOCTYPE html>
<html>
<head>
<title>Not Found</title>
<style>
    body {
        width: 35em;
        margin: 0 auto;
        font-family: Tahoma, Verdana, Arial, sans-serif;
    }
</style>
</head>
<body>
<h1>The page you requested was not found.</h1>
<p>Sorry, the page you are looking for is currently unavailable.<br/>
Please try again later.</p>
<p>The server is powered by <a href="https://github.com/fatedier/frp">frp</a>.</p>
<p><em>Faithfully yours, frp.</em></p>
</body>
</html>
`
)

func (p CustomErrorPage) contentType() string {
	if p.ContentType != "" {
		return p.ContentType
	}
	return "text/html"
}

// resolveNotFoundPage returns the error page used for 404 responses. A custom
// page file (NotFoundPagePath) takes precedence over a customErrorPages entry
// with status code 404, which in turn takes precedence over the built-in
// default page.
func resolveNotFoundPage() CustomErrorPage {
	if NotFoundPagePath != "" {
		buf, err := os.ReadFile(NotFoundPagePath)
		if err != nil {
			log.Warnf("read custom 404 page error: %v", err)
		} else {
			return CustomErrorPage{Body: string(buf)}
		}
	}
	if p, ok := customErrorPages[http.StatusNotFound]; ok {
		return p
	}
	return CustomErrorPage{Body: NotFound}
}

// writeErrorPage writes statusCode and the given error page to rw.
func writeErrorPage(rw http.ResponseWriter, statusCode int, p CustomErrorPage) {
	for k, v := range p.Headers {
		rw.Header().Set(k, v)
	}
	rw.Header().Set("server", "frp/"+version.Full())
	rw.Header().Set("Content-Type", p.contentType())
	rw.WriteHeader(statusCode)
	_, _ = rw.Write([]byte(p.Body))
}

// writeCustomErrorPage writes the custom error page registered for statusCode
// to rw. It reports whether a custom page was written.
func writeCustomErrorPage(rw http.ResponseWriter, statusCode int) bool {
	p, ok := customErrorPages[statusCode]
	if !ok {
		return false
	}
	writeErrorPage(rw, statusCode, p)
	return true
}

func NotFoundResponse() *http.Response {
	p := resolveNotFoundPage()

	header := make(http.Header)
	for k, v := range p.Headers {
		header.Set(k, v)
	}
	header.Set("server", "frp/"+version.Full())
	header.Set("Content-Type", p.contentType())

	content := []byte(p.Body)
	res := &http.Response{
		Status:        "Not Found",
		StatusCode:    404,
		Proto:         "HTTP/1.1",
		ProtoMajor:    1,
		ProtoMinor:    1,
		Header:        header,
		Body:          io.NopCloser(bytes.NewReader(content)),
		ContentLength: int64(len(content)),
	}
	return res
}
